/**
 * Web Push (RFC 8030) with aes128gcm payload encryption (RFC 8291) and VAPID
 * authentication (RFC 8292), implemented with WebCrypto and fetch only.
 *
 * The `web-push` npm package depends on node:https and node:crypto ECDH, which
 * Cloudflare Workers do not provide, so it cannot send notifications from here.
 */

export interface PushSubscriptionKeys {
  endpoint: string
  /** Browser's P-256 public key (65 byte uncompressed point), base64 or base64url */
  p256dh: string
  /** 16 byte auth secret, base64 or base64url */
  auth: string
}

export interface VapidDetails {
  /** `mailto:` or `https:` contact; a bare email address gets `mailto:` prepended */
  subject: string
  /** 65 byte uncompressed P-256 public key, base64url (as generated by `web-push generate-vapid-keys`) */
  publicKey: string
  /** 32 byte P-256 private scalar, base64url */
  privateKey: string
}

export interface SendPushOptions {
  /** Seconds the push service should keep the message if the device is offline */
  ttl?: number
  urgency?: 'very-low' | 'low' | 'normal' | 'high'
  /** Replaces an undelivered message with the same topic */
  topic?: string
}

export class WebPushError extends Error {
  constructor(
    message: string,
    readonly statusCode: number,
    readonly body: string,
    readonly endpoint: string
  ) {
    super(message)
    this.name = 'WebPushError'
  }

  /** The subscription no longer exists and should be deleted */
  get isGone() {
    return this.statusCode === 404 || this.statusCode === 410
  }
}

const encoder = new TextEncoder()
const RECORD_SIZE = 4096

export function base64UrlDecode(value: string): Uint8Array {
  const base64 = value.trim().replace(/-/g, '+').replace(/_/g, '/')
  const padded = base64 + '='.repeat((4 - (base64.length % 4)) % 4)
  const binary = atob(padded)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
  return bytes
}

export function base64UrlEncode(bytes: Uint8Array | ArrayBuffer): string {
  const view = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes)
  let binary = ''
  for (let i = 0; i < view.length; i++) binary += String.fromCharCode(view[i])
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '')
}

function concat(...parts: Uint8Array[]): Uint8Array<ArrayBuffer> {
  const out = new Uint8Array(parts.reduce((sum, p) => sum + p.length, 0))
  let offset = 0
  for (const part of parts) {
    out.set(part, offset)
    offset += part.length
  }
  return out
}

async function hkdf(
  salt: Uint8Array,
  ikm: Uint8Array,
  info: Uint8Array,
  length: number
): Promise<Uint8Array<ArrayBuffer>> {
  const key = await crypto.subtle.importKey(
    'raw',
    new Uint8Array(ikm),
    'HKDF',
    false,
    ['deriveBits']
  )
  const bits = await crypto.subtle.deriveBits(
    {
      name: 'HKDF',
      hash: 'SHA-256',
      salt: new Uint8Array(salt),
      info: new Uint8Array(info)
    },
    key,
    length * 8
  )
  return new Uint8Array(bits)
}

/**
 * Encrypts a payload for a push subscription using the aes128gcm content
 * encoding (single record). Returns the full request body.
 */
export async function encryptPayload(
  payload: Uint8Array,
  subscription: Pick<PushSubscriptionKeys, 'p256dh' | 'auth'>,
  /** Only for tests: fixed sender key pair and salt */
  overrides?: { localKeyPair?: CryptoKeyPair; salt?: Uint8Array }
): Promise<Uint8Array<ArrayBuffer>> {
  const uaPublic = new Uint8Array(base64UrlDecode(subscription.p256dh))
  const authSecret = new Uint8Array(base64UrlDecode(subscription.auth))

  if (uaPublic.length !== 65 || uaPublic[0] !== 0x04) {
    throw new Error('Invalid subscription p256dh key')
  }
  if (authSecret.length < 16) {
    throw new Error('Invalid subscription auth secret')
  }

  const localKeyPair =
    overrides?.localKeyPair ??
    ((await crypto.subtle.generateKey(
      { name: 'ECDH', namedCurve: 'P-256' },
      true,
      ['deriveBits']
    )) as CryptoKeyPair)
  const asPublic = new Uint8Array(
    (await crypto.subtle.exportKey(
      'raw',
      localKeyPair.publicKey
    )) as ArrayBuffer
  )

  const uaKey = await crypto.subtle.importKey(
    'raw',
    uaPublic,
    { name: 'ECDH', namedCurve: 'P-256' },
    false,
    []
  )
  const ecdhSecret = new Uint8Array(
    await crypto.subtle.deriveBits(
      // workers-types call this field `$public`, the runtime expects `public`
      {
        name: 'ECDH',
        public: uaKey
      } as unknown as Parameters<SubtleCrypto['deriveBits']>[0],
      localKeyPair.privateKey,
      256
    )
  )

  const ikm = await hkdf(
    authSecret,
    ecdhSecret,
    concat(encoder.encode('WebPush: info\0'), uaPublic, asPublic),
    32
  )

  const salt = new Uint8Array(
    overrides?.salt ?? crypto.getRandomValues(new Uint8Array(16))
  )
  const cek = await hkdf(
    salt,
    ikm,
    encoder.encode('Content-Encoding: aes128gcm\0'),
    16
  )
  const nonce = await hkdf(
    salt,
    ikm,
    encoder.encode('Content-Encoding: nonce\0'),
    12
  )

  // Single (last) record: plaintext followed by the 0x02 padding delimiter
  const plaintext = concat(payload, new Uint8Array([0x02]))
  if (plaintext.length + 16 > RECORD_SIZE) {
    throw new Error('Push payload is too large')
  }

  const aesKey = await crypto.subtle.importKey('raw', cek, 'AES-GCM', false, [
    'encrypt'
  ])
  const ciphertext = new Uint8Array(
    await crypto.subtle.encrypt(
      { name: 'AES-GCM', iv: nonce },
      aesKey,
      plaintext
    )
  )

  const header = new Uint8Array(16 + 4 + 1 + asPublic.length)
  header.set(salt, 0)
  new DataView(header.buffer).setUint32(16, RECORD_SIZE)
  header[20] = asPublic.length
  header.set(asPublic, 21)

  return concat(header, ciphertext)
}

function normalizeSubject(subject: string) {
  const trimmed = subject.trim()
  if (/^(mailto|https):/i.test(trimmed)) return trimmed
  if (trimmed.includes('@')) return `mailto:${trimmed}`
  return trimmed
}

async function importVapidPrivateKey(vapid: VapidDetails) {
  const publicKey = base64UrlDecode(vapid.publicKey)
  const privateKey = base64UrlDecode(vapid.privateKey)
  if (publicKey.length !== 65 || publicKey[0] !== 0x04) {
    throw new Error('VAPID public key must be a 65 byte uncompressed P-256 key')
  }
  if (privateKey.length !== 32) {
    throw new Error('VAPID private key must be a 32 byte P-256 key')
  }

  return crypto.subtle.importKey(
    'jwk',
    {
      kty: 'EC',
      crv: 'P-256',
      x: base64UrlEncode(publicKey.slice(1, 33)),
      y: base64UrlEncode(publicKey.slice(33, 65)),
      d: base64UrlEncode(privateKey),
      ext: true
    },
    { name: 'ECDSA', namedCurve: 'P-256' },
    false,
    ['sign']
  )
}

/** Builds the `Authorization` header value for a push service endpoint */
export async function createVapidAuthorization(
  endpoint: string,
  vapid: VapidDetails,
  expiresInSeconds = 12 * 60 * 60
): Promise<string> {
  const key = await importVapidPrivateKey(vapid)
  const header = base64UrlEncode(
    encoder.encode(JSON.stringify({ typ: 'JWT', alg: 'ES256' }))
  )
  const claims = base64UrlEncode(
    encoder.encode(
      JSON.stringify({
        aud: new URL(endpoint).origin,
        exp: Math.floor(Date.now() / 1000) + expiresInSeconds,
        sub: normalizeSubject(vapid.subject)
      })
    )
  )
  const unsigned = `${header}.${claims}`
  // WebCrypto returns the raw r||s signature that JWS ES256 expects
  const signature = await crypto.subtle.sign(
    { name: 'ECDSA', hash: 'SHA-256' },
    key,
    encoder.encode(unsigned)
  )
  const jwt = `${unsigned}.${base64UrlEncode(signature)}`
  return `vapid t=${jwt}, k=${base64UrlEncode(base64UrlDecode(vapid.publicKey))}`
}

export async function sendPushNotification(
  subscription: PushSubscriptionKeys,
  payload: string,
  vapid: VapidDetails,
  options: SendPushOptions = {}
): Promise<Response> {
  const body = await encryptPayload(encoder.encode(payload), subscription)
  const headers: Record<string, string> = {
    Authorization: await createVapidAuthorization(subscription.endpoint, vapid),
    TTL: String(options.ttl ?? 24 * 60 * 60),
    Urgency: options.urgency ?? 'normal',
    'Content-Encoding': 'aes128gcm',
    'Content-Type': 'application/octet-stream'
  }
  if (options.topic) headers.Topic = options.topic

  const response = await fetch(subscription.endpoint, {
    method: 'POST',
    headers,
    body
  })

  if (!response.ok) {
    const text = await response.text().catch(() => '')
    throw new WebPushError(
      `Push service responded with ${response.status}: ${text}`,
      response.status,
      text,
      subscription.endpoint
    )
  }

  return response
}

/** Generates a VAPID key pair in the format expected by `VapidDetails` */
export async function generateVapidKeys() {
  const keyPair = (await crypto.subtle.generateKey(
    { name: 'ECDSA', namedCurve: 'P-256' },
    true,
    ['sign', 'verify']
  )) as CryptoKeyPair
  const publicKey = (await crypto.subtle.exportKey(
    'raw',
    keyPair.publicKey
  )) as ArrayBuffer
  const jwk = (await crypto.subtle.exportKey(
    'jwk',
    keyPair.privateKey
  )) as JsonWebKey
  return {
    publicKey: base64UrlEncode(publicKey),
    privateKey: jwk.d!
  }
}
